export function getEnvironmentSpec(id: EnvironmentId): EnvironmentSpec {
  return ENVIRONMENTS.find((e) => e.id === id) ?? ENVIRONMENTS[0];
}

export function getBicycleSpec(id: string): BicycleSpec {
  return BICYCLES.find((b) => b.id === id) ?? BICYCLES[0];
}

export function getOutfitSpec(id: string): OutfitSpec {
  return OUTFITS.find((o) => o.id === id) ?? OUTFITS[0];
}

export function getSkinSpec(id: string): SkinSpec {
  return SKINS.find((s) => s.id === id) ?? SKINS[0];
}

export function getEffectSpec(id: string): EffectSpec {
  return EFFECTS.find((e) => e.id === id) ?? EFFECTS[0];
}
